# PRECEDENCE
# ======================================================================

def calculate_precedence(
    events
):

    rows = []

    for side in [
        "left",
        "right",
    ]:

        g = events[
            events["side"] == side
        ].copy()

        # A and B must both exist
        complete_AB = g[
            g["A_distance"].notna()
            &
            g["B_distance"].notna()
        ].copy()

        if complete_AB.empty:

            rows.append(
                {
                    "side": side,
                    "n": 0,
                    "A_before_B": np.nan,
                    "median_A": np.nan,
                    "median_B": np.nan,
                    "median_lead": np.nan,
                }
            )

            continue

        lead = (
            complete_AB["B_distance"]
            -
            complete_AB["A_distance"]
        )

        A_before_B = (
            lead > 0
        )

        rows.append(
            {
                "side":
                    side,

                "n":
                    len(complete_AB),

                "A_before_B":
                    float(
                        A_before_B.mean()
                    ),

                "median_A":
                    float(
                        complete_AB[
                            "A_distance"
                        ].median()
                    ),

                "median_B":
                    float(
                        complete_AB[
                            "B_distance"
                        ].median()
                    ),

                "median_lead":
                    float(
                        lead.median()
                    ),
            }
        )

    return pd.DataFrame(
        rows
    )


# ======================================================================
# HORIZON ANALYSIS
# ======================================================================

def calculate_horizon_rates(
    events
):

    rows = []

    for side in [
        "left",
        "right",
    ]:

        g = events[
            events["side"] == side
        ].copy()

        g = g[
            g["A_distance"].notna()
            &
            g["B_distance"].notna()
        ].copy()

        if g.empty:
            continue

        lead = (
            g["B_distance"]
            -
            g["A_distance"]
        )

        for horizon in HORIZONS:

            positive = (
                lead >= horizon
            )

            rate = (
                positive.mean()
            )

            rows.append(
                {
                    "side":
                        side,

                    "horizon":
                        horizon,

                    "n":
                        len(g),

                    "n_warning":
                        int(
                            positive.sum()
                        ),

                    "warning_rate":
                        float(rate),

                    "median_lead":
                        float(
                            lead.median()
                        ),
                }
            )

    return pd.DataFrame(
        rows
    )


# ======================================================================
# BOOTSTRAP CI
# ======================================================================

def bootstrap_proportion_ci(
    values,
    iterations=BOOTSTRAP_ITERATIONS,
    seed=RANDOM_SEED
):

    values = np.asarray(
        values,
        dtype=float
    )

    values = values[
        np.isfinite(values)
    ]

    if len(values) == 0:

        return (
            np.nan,
            np.nan
        )

    rng = np.random.default_rng(
        seed
    )

    n = len(values)

    boot = np.empty(
        iterations,
        dtype=float
    )

    for i in range(
        iterations
    ):

        sample = rng.choice(
            values,
            size=n,
            replace=True
        )

        boot[i] = np.mean(
            sample
        )

    return (
        float(
            np.quantile(
                boot,
                0.025
            )
        ),
        float(
            np.quantile(
                boot,
                0.975
            )
        ),
    )


# ======================================================================
# PERMUTATION TEST
# ======================================================================

def permutation_horizon_test(
    events,
    horizon,
    side,
    n_permutations=N_PERMUTATIONS,
    seed=RANDOM_SEED
):

    """
    Null hypothesis:

        A and B boundary locations are exchangeable.

    We shuffle A/B labels within each expression.

    Test statistic:

        proportion with B-A >= horizon

    One-sided permutation p-value.
    """

    g = events[
        events["side"] == side
    ].copy()

    g = g[
        g["A_distance"].notna()
        &
        g["B_distance"].notna()
    ].copy()

    if g.empty:

        return {
            "side": side,
            "horizon": horizon,
            "observed": np.nan,
            "p_value": np.nan,
            "n": 0,
        }

    A = (
        g["A_distance"]
        .to_numpy(
            dtype=float
        )
    )

    B = (
        g["B_distance"]
        .to_numpy(
            dtype=float
        )
    )

    observed = np.mean(
        (B - A) >= horizon
    )

    rng = np.random.default_rng(
        seed
    )

    count = 0

    for _ in range(
        n_permutations
    ):

        swap = (
            rng.random(
                len(A)
            )
            < 0.5
        )

        A_perm = np.where(
            swap,
            B,
            A
        )

        B_perm = np.where(
            swap,
            A,
            B
        )

        statistic = np.mean(
            (B_perm - A_perm)
            >= horizon
        )

        if statistic >= observed:

            count += 1

    p_value = (
        count + 1
    ) / (
        n_permutations + 1
    )

    return {
        "side":
            side,

        "horizon":
            horizon,

        "observed":
            float(observed),

        "p_value":
            float(p_value),

        "n":
            len(g),

        "permutations":
            n_permutations,
    }


