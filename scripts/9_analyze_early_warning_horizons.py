"""
EARLY-WARNING HORIZON ANALYSIS — FIXED

Purpose
-------
Measure whether representation drift (A) precedes prediction failure (B),
and quantify how many viewpoint degrees of warning are available.

IMPORTANT
---------
The viewpoint axis is centered at the frontal reference viewpoint:

    frontal = 107°

LEFT:
    107 -> 106 -> ... -> 0

RIGHT:
    107 -> 108 -> ... -> 214

For both sides, distance from frontal is represented as a positive
distance-from-frontal coordinate.

Therefore:

    A_distance < B_distance

means:

    representation drift happened before prediction failure.

The script does NOT assume A < C < B.

It independently detects:

    A = representation instability boundary
    C = confidence / margin boundary
    B = prediction failure boundary

and reports the observed ordering.

No causality is claimed.
"""

