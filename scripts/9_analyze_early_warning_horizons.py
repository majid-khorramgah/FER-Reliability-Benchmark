def largest_supported_horizon(
    horizon_rates,
    side,
    minimum_rate
):

    g = horizon_rates[
        horizon_rates["side"]
        == side
    ].copy()

    g = g[
        g["warning_rate"]
        >= minimum_rate
    ]

    if g.empty:

        return np.nan

    return float(
        g["horizon"].max()
    )


