def load_thresholds():

    """
    Prefer thresholds generated by previous trajectory analysis.

    If unavailable, use the values already established in the project.
    """

    defaults = {

        "A_angular": 13.43702602,

        "C_margin": 0.00237080,

    }

    candidates = [

        ANALYSIS_DIR
        / "trajectory_analysis_report.json",

        ANALYSIS_DIR
        / "trajectory_analysis_report_multimetric.json",

        ANALYSIS_DIR
        / "trajectory_analysis_report.json",

    ]

    for path in candidates:

        if not path.exists():
            continue

        try:

            with open(
                path,
                "r",
                encoding="utf-8"
            ) as f:

                data = json.load(f)

            possible = [

                data.get("thresholds"),

                data.get("robust_thresholds"),

                data.get("ROBUST_THRESHOLDS"),

            ]

            for block in possible:

                if not isinstance(block, dict):
                    continue

                for key in block:

                    low = str(key).lower()

                    if "angular" in low:

                        try:

                            defaults["A_angular"] = float(
                                block[key]
                            )

                        except Exception:
                            pass

                    if "margin" in low:

                        try:

                            defaults["C_margin"] = float(
                                block[key]
                            )

                        except Exception:
                            pass

        except Exception:

            pass

    return defaults


# ======================================================================
# VIEWPOINT -> SIDE
# ======================================================================

def viewpoint_side(viewpoint: int):

    """
    Determine side relative to frontal viewpoint.

    107 = frontal

    0..106  -> left
    108..214 -> right
    """

    viewpoint = int(viewpoint)

    if viewpoint < FRONTAL_VIEWPOINT:

        return "left"

    if viewpoint > FRONTAL_VIEWPOINT:

        return "right"

    return "frontal"


# ======================================================================
# VIEWPOINT -> DISTANCE FROM FRONTAL
# ======================================================================

def distance_from_frontal(viewpoint: int):

    """
    Absolute viewpoint distance from frontal.

    Example:

        viewpoint 100 -> 7°
        viewpoint 114 -> 7°

    This is exactly what we need to compare left and right
    warning horizons on the same coordinate system.
    """

    return abs(
        int(viewpoint) - FRONTAL_VIEWPOINT
    )


# ======================================================================
# DIRECTED DISTANCE
# ======================================================================

def directed_distance(viewpoint: int):

    """
    Return positive distance along the correct side.

    Left:

        107 -> 106 -> ... -> 0

    Right:

        107 -> 108 -> ... -> 214

    Both become:

        1, 2, 3, ... 107

    """

    return abs(
        int(viewpoint) - FRONTAL_VIEWPOINT
    )


