# ======================================================================
# PREDICTION FAILURE
# ======================================================================

def determine_prediction_failure(
    group: pd.DataFrame
):

    """
    B = prediction failure.

    In this dataset, B_predicted_folder is expected to encode
    the model's predicted folder.

    We infer the correct expression/folder from the current sequence.

    Prediction failure means:

        predicted folder != true folder

    If B column already contains a boolean-like value, use it directly.
    """

    g = group.copy()

    true_folder = (
        g["_folder"]
        .iloc[0]
    )

    b = (
        g["_B"]
        .astype(str)
        .str.strip()
        .str.lower()
    )

    # Boolean-like B
    boolean_true = {
        "true",
        "1",
        "yes",
        "failure",
        "fail",
        "incorrect",
        "wrong",
    }

    boolean_false = {
        "false",
        "0",
        "no",
        "correct",
        "ok",
        "right",
    }

    if b.isin(
        boolean_true | boolean_false
    ).all():

        failure = b.isin(
            boolean_true
        )

    else:

        failure = (
            g["_B"].astype(str).str.strip()
            != str(true_folder).strip()
        )

    g["_B_failure"] = failure.astype(bool)

    return g


# ======================================================================
# SUSTAINED FIRST CROSSING
# ======================================================================

def first_sustained_crossing(
    distances,
    condition,
    sustained=3
):

    """
    Find the first distance at which condition remains true for
    at least `sustained` consecutive viewpoints.

    The data must already be ordered by increasing distance.

    Returns None if no sustained crossing exists.
    """

    distances = np.asarray(
        distances,
        dtype=float
    )

    condition = np.asarray(
        condition,
        dtype=bool
    )

    n = len(condition)

    if n == 0:
        return None

    if n < sustained:
        return None

    for i in range(
        0,
        n - sustained + 1
    ):

        window = condition[
            i:i + sustained
        ]

        if np.all(window):

            return float(
                distances[i]
            )

    return None


# ======================================================================
# BUILD EVENT SEQUENCE
# ======================================================================

def build_sequence_events(
    df: pd.DataFrame,
    thresholds
):

    section(
        "BUILDING SEQUENCE EVENTS"
    )

    sequences = []

    grouped = list(
        df.groupby(
            "_folder",
            sort=True
        )
    )

    print(
        f"Total folders: {len(grouped)}"
    )

    for index, (
        folder,
        group
    ) in enumerate(
        grouped,
        start=1
    ):

        if (
            index <= 5
            or index % 50 == 0
            or index == len(grouped)
        ):

            print(
                f"Processed "
                f"{index}/{len(grouped)}"
            )

        g = group.copy()

        # --------------------------------------------------------------
        # Required viewpoint coverage
        # --------------------------------------------------------------

        unique_views = set(
            g["_viewpoint"]
            .astype(int)
            .tolist()
        )

        complete = (
            len(unique_views)
            == EXPECTED_VIEWPOINTS
            and
            unique_views
            == set(
                range(
                    MIN_VIEWPOINT,
                    MAX_VIEWPOINT + 1
                )
            )
        )

        if not complete:

            continue

        # --------------------------------------------------------------
        # Prediction failure
        # --------------------------------------------------------------

        g = determine_prediction_failure(
            g
        )

        expression_name = (
            g["_expression"]
            .iloc[0]
        )

        for side in [
            "left",
            "right",
        ]:

            side_g = g[
                g["_side"] == side
            ].copy()

            if side_g.empty:

                continue

            # ----------------------------------------------------------
            # IMPORTANT:
            # Always sort by distance FROM FRONTAL.
            # ----------------------------------------------------------

            side_g = side_g.sort_values(
                "_distance"
            )

            distances = (
                side_g["_distance"]
                .to_numpy(
                    dtype=float
                )
            )

            A_values = (
                side_g["_A"]
                .to_numpy(
                    dtype=float
                )
            )

            C_values = (
                side_g["_C"]
                .to_numpy(
                    dtype=float
                )
            )
            B_failure = (
                side_g["_B_failure"]
                .to_numpy(
                    dtype=bool
                )
            )

            # ----------------------------------------------------------
            # A event
            # ----------------------------------------------------------

            A_condition = (
                A_values
                >= thresholds["A_angular"]
            )

            A_distance = (
                first_sustained_crossing(
                    distances,
                    A_condition,
                    SUSTAINED_VIEWPOINTS
                )
            )

            # ----------------------------------------------------------
            # C event
            #
            # C is a margin instability.
            #
            # Smaller margin = less confidence.
            # ----------------------------------------------------------

            C_condition = (
                C_values
                <= thresholds["C_margin"]
            )

            C_distance = (
                first_sustained_crossing(
                    distances,
                    C_condition,
                    SUSTAINED_VIEWPOINTS
                )
            )

            # ----------------------------------------------------------
            # B event
            # ----------------------------------------------------------

            B_distance = (
                first_sustained_crossing(
                    distances,
                    B_failure,
                    SUSTAINED_VIEWPOINTS
                )
            )

            # ----------------------------------------------------------
            # Save
            # ----------------------------------------------------------

            sequences.append(
                {
                    "expression":
                        expression_name,

                    "folder":
                        folder,

                    "side":
                        side,

                    "A_distance":
                        A_distance,

                    "C_distance":
                        C_distance,

                    "B_distance":
                        B_distance,

                    "complete":
                        True,
                }
            )

    events = pd.DataFrame(
        sequences
    )

    print()
    print(
        f"Sequences analyzed: "
        f"{events['folder'].nunique()}"
    )

    return events


