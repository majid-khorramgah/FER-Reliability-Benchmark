def find_column(
    df: pd.DataFrame,
    candidates,
    required=True
):

    normalized = {
        str(c).strip().lower(): c
        for c in df.columns
    }

    for candidate in candidates:

        key = candidate.strip().lower()

        if key in normalized:
            return normalized[key]

    # More tolerant matching
    for col in df.columns:

        low = str(col).strip().lower()

        for candidate in candidates:

            if candidate.strip().lower() in low:

                return col

    if required:

        raise KeyError(
            f"Could not find required column. "
            f"Tried: {candidates}"
        )

    return None


